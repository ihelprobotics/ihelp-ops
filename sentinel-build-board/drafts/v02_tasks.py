src = SRC.read_text(encoding="utf-8")
m = re.search(r'(id="board-data">)(.*?)(</script>)', src, re.S)
v01 = json.loads(m.group(2))
old = {t["id"]: t for t in v01["tasks"]}

tasks, errors = [], []
for (tid, epic, title, what, deliv, done, deps, size, skills, gate, prio) in T:
    o = old.get(tid)
    tasks.append({
        "id": tid, "epic": epic, "title": title, "what": what, "deliv": deliv, "done": done,
        "deps": deps, "size": size, "skills": skills, "gate": gate, "assignee": "",
        # Kept ids keep their v0.1 status and evidence; new slices start at To do.
        "status": o["status"] if o else "To do",
        "priority": prio, "due": "",
        "evidence": o["evidence"] if o else "",
        "notes": "" if o else "",
    })

ids = [t["id"] for t in tasks]
if len(ids) != len(set(ids)):
    errors.append("duplicate ids")
missing = set(old) - set(ids)
if missing:
    errors.append(f"v0.1 ids dropped: {sorted(missing)}")
known = set(ids)
gates = {d["id"] for d in v01["decisions"]}
graph = {}
for t in tasks:
    if t["size"] not in ("S", "M"):
        errors.append(f'{t["id"]}: size {t["size"]}')
    if t["gate"] != "—" and t["gate"] not in gates:
        errors.append(f'{t["id"]}: unknown gate {t["gate"]}')
    d = [] if t["deps"] == "—" else [x.strip() for x in t["deps"].split(",")]
    for x in d:
        if x not in known:
            errors.append(f'{t["id"]}: unknown dependency {x}')
    graph[t["id"]] = d
seen, stack = set(), set()
def visit(n, path):
    if n in stack:
        errors.append("cycle: " + " -> ".join(path + [n])); return
    if n in seen: return
    stack.add(n)
    for x in graph.get(n, []): visit(x, path + [n])
    stack.discard(n); seen.add(n)
for n in graph: visit(n, [])
if errors:
    sys.exit("\n".join(errors))

